"""Состояния заказа — единственный источник правды.

Раньше список состояний был в двух местах: витрина знала «Ждёт оплаты» и
«Принят», панель оператора — ещё четыре. Оператор переводил заказ в «Собирается»,
а покупатель видел «В работе», потому что в его словаре такого состояния просто
не было. Отменённый заказ выглядел точно так же — «в работе».

Поэтому состояния описаны здесь один раз, и обе стороны берут их отсюда.
Добавляя новое состояние, правьте только этот файл.
"""

# Что видит покупатель. Формулировки его, а не учётные: «Собирается» понятнее,
# чем ASSEMBLING, и не требует пояснений.
TEXT = {
    "NEW": "Ждёт оплаты",
    "CONFIRMED": "Принят",
    "ASSEMBLING": "Собирается",
    "DELIVERING": "В доставке",
    "DONE": "Выполнен",
    "CANCELED": "Отменён",
}

# Из какого состояния куда можно перейти. Без этого оператор случайным нажатием
# вернёт выполненный заказ в сборку, и отчёты разойдутся с фактом.
TRANSITIONS = {
    "NEW": {"CONFIRMED", "CANCELED"},
    "CONFIRMED": {"ASSEMBLING", "CANCELED"},
    "ASSEMBLING": {"DELIVERING", "CANCELED"},
    "DELIVERING": {"DONE", "CANCELED"},
    "DONE": set(),
    "CANCELED": set(),
}

# Заказ с оплатой наличными сразу уходит в магазин, онлайн — ждёт подтверждения
# платежа и передаётся на сборку только после него (BR-13).
BY_PAYMENT = {"cash": "CONFIRMED", "online": "NEW"}

# Состояния, после которых с заказом уже ничего не происходит.
FINAL = {"DONE", "CANCELED"}


def text(status: str) -> str:
    """Название состояния для покупателя. Незнакомое состояние не выдумываем,
    а показываем как есть: молчаливое «В работе» однажды уже скрыло отмену."""
    return TEXT.get(status, status)
