"""Состояния заказа — единственный источник правды.

Раньше список состояний был в двух местах: витрина знала «Ждёт оплаты» и
«Принят», панель оператора — ещё четыре. Оператор переводил заказ в «Собирается»,
а покупатель видел «В работе», потому что в его словаре такого состояния просто
не было. Отменённый заказ выглядел точно так же — «в работе».

Поэтому состояния описаны здесь один раз, и обе стороны берут их отсюда.
Добавляя новое состояние, правьте только этот файл.
"""

# Что видит покупатель. Формулировки его, а не учётные: «Собирается» понятнее,
# чем ASSEMBLING, и не требует пояснений.
TEXT = {
    "NEW": "Ждёт оплаты",
    "CONFIRMED": "Принят",
    "ASSEMBLING": "Собирается",
    "DELIVERING": "В доставке",
    "DONE": "Выполнен",
    "CANCELED": "Отменён",
}

# Из какого состояния куда можно перейти. Без этого оператор случайным нажатием
# вернёт выполненный заказ в сборку, и отчёты разойдутся с фактом.
TRANSITIONS = {
    "NEW": {"CONFIRMED", "CANCELED"},
    "CONFIRMED": {"ASSEMBLING", "CANCELED"},
    "ASSEMBLING": {"DELIVERING", "CANCELED"},
    "DELIVERING": {"DONE", "CANCELED"},
    "DONE": set(),
    "CANCELED": set(),
}

# Заказ с оплатой наличными сразу уходит в магазин, онлайн — ждёт подтверждения
# платежа и передаётся на сборку только после него (BR-13).
BY_PAYMENT = {"cash": "CONFIRMED", "online": "NEW"}

# Состояния, после которых с заказом уже ничего не происходит.
FINAL = {"DONE", "CANCELED"}


def text(status: str) -> str:
    """Название состояния для покупателя. Незнакомое состояние не выдумываем,
    а показываем как есть: молчаливое «В работе» однажды уже скрыло отмену."""
    return TEXT.get(status, status)


def move(db, order, to: str, *, unpaid_only: bool = False, values: dict | None = None,
         where: list | None = None) -> bool:
    """Переводит заказ в состояние to — только если он всё ещё в том, в котором
    мы его прочитали. Возвращает, удалось ли.

    Статус меняют сразу несколько участников: оператор в панели, синхронизация
    с кассой, автоотмена неоплаченных и уведомление об оплате. Каждый сначала
    читает заказ, потом пишет. Обычное присваивание пишет вслепую, и последний
    побеждает: автоотмена, прочитавшая заказ за миг до оплаты, записала бы
    «Отменён» поверх «Оплачен». Поэтому запись условная — UPDATE … WHERE status
    = прочитанный, — и проигравший узнаёт об этом по нулю изменённых строк.

    unpaid_only — ещё и «пока не оплачен»: так уведомление об оплате не проведёт
    платёж дважды, а автоотмена не отменит оплаченный. where — прочие условия,
    которые должны быть верны в момент записи, а не в момент чтения.

    После записи объект перечитывается из базы — и при успехе, и при неудаче.
    По умолчанию SQLAlchemy применила бы UPDATE к объекту в памяти по его
    старому статусу даже тогда, когда в базе не изменилась ни одна строка,
    и код, прочитавший потом order.status, увидел бы состояние, которого нет.
    """
    from sqlalchemy import update

    from app.models import Order

    stmt = update(Order).where(Order.id == order.id, Order.status == order.status)
    if unpaid_only:
        stmt = stmt.where(Order.paid_at.is_(None))
    for condition in where or []:
        stmt = stmt.where(condition)
    stmt = stmt.values(status=to, **(values or {})).execution_options(
        synchronize_session=False)
    changed = db.execute(stmt).rowcount
    db.refresh(order)
    return changed == 1
