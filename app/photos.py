"""Адреса фотографий товаров.

Файл называется по id карточки — {product_id}.jpg — чтобы код REGOS не попадал
в публичный адрес (BR-36). У этого есть обратная сторона: при замене фотографии
имя файла не меняется, а статика отдаётся с кешем на неделю. Покупатель ещё
семь дней видел бы старый снимок, и администратор решил бы, что загрузка
не работает.

Поэтому к адресу дописывается время изменения файла: заменили картинку —
адрес стал другим, кеш промахнулся. Ровно так же в index.html подставляется
версия к app.js.
"""
import os
from pathlib import Path

# Каталог с фотографиями вынесен из дерева кода. Иначе выкладка новой версии
# (код едет архивом поверх каталога приложения) затирает загруженные админом
# картинки теми, что лежат в репозитории: имена совпадают, это id товара.
# В репозитории остаётся только начальный набор — он копируется при установке.
DIR = Path(os.getenv("PHOTO_DIR") or Path(__file__).resolve().parent.parent / "static" / "img")
PREFIX = "/static/img/"


def url(filename: str | None) -> str | None:
    """Адрес картинки с отметкой версии. Нет файла — нет и адреса: показывать
    битую ссылку хуже, чем заглушку."""
    if not filename:
        return None
    path = DIR / filename
    try:
        version = int(path.stat().st_mtime)
    except OSError:
        # файла нет: карточка ссылается на удалённую картинку
        return None
    return f"{PREFIX}{filename}?v={version}"


def remove(filename: str | None) -> None:
    """Удаляет файл картинки. Отсутствующий файл ошибкой не считаем:
    задача — чтобы его не было."""
    if not filename:
        return
    (DIR / filename).unlink(missing_ok=True)
