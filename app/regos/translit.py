"""Транслитерация имён для карточки покупателя в REGOS.

Вынужденная мера. API REGOS не принимает кириллицу в полях имени покупателя:
RetailCustomer/Add и /Edit отвечают ошибкой 9999 «Unknown error: unexpected
failure» на любое русское или узбекское имя, а на латиницу — работают.
Проверено на живом аккаунте: «Иван» падает, «Ivan» проходит; то же с фамилией
и при редактировании уже созданной карточки. Та же беда у DeliveryType/Add.

Без карточки покупателя касса показывает пустые «Покупатель» и «Телефон» —
кассиру и курьеру не с чем работать. Поэтому имя переводим в латиницу,
а исходное, как есть, остаётся в описании документа заказа: там кириллица
принимается нормально.

Когда REGOS починит приём кириллицы, этот модуль надо выбросить, а вызов
заменить на передачу имени как есть.
"""

# Узбекская кириллица отличается от русской несколькими буквами (ў, қ, ғ, ҳ),
# поэтому они тоже в таблице.
MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "j", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    "ў": "o", "қ": "q", "ғ": "g", "ҳ": "h",
}


def to_latin(text: str) -> str:
    """«Жавохир Журакулов» -> «Javokhir Jurakulov».

    Регистр первой буквы каждого слова сохраняем: имя должно читаться.
    Символы, которых нет в таблице (латиница, цифры, дефисы, пробелы),
    проходят как есть.
    """
    out: list[str] = []
    for char in text:
        lower = char.lower()
        replacement = MAP.get(lower)
        if replacement is None:
            out.append(char)
            continue
        if char.isupper() and replacement:
            replacement = replacement[0].upper() + replacement[1:]
        out.append(replacement)
    return "".join(out).strip()


def customer_name(name: str) -> tuple[str, str | None]:
    """Разбивает имя покупателя на имя и фамилию для карточки REGOS.

    first_name у них обязательный, last_name — нет. Пустое имя недопустимо,
    поэтому на всякий случай подставляем заглушку: заказ без карточки
    покупателя хуже, чем карточка с невнятным именем.
    """
    latin = to_latin(name or "")
    parts = [p for p in latin.split() if p]
    if not parts:
        return "Pokupatel", None
    return parts[0], " ".join(parts[1:]) or None
